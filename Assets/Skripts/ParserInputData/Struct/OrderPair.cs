public struct OrderPair {
    /// <summary>
    ///  Класс хранит в себе порядок между 2 точками, которые получил из файла
    ///  Нужен для промежуточного упорядочевания
    /// </summary>
   
    // Эти строки позволяют задавать значения без создания конструктора
    public string Inf { get; set; }
    public string Sup { get; set; }
    // Зададим значение для каждой связи, если > 0 то левая больше правого
    // иначе правая больше левого
    public short Value { get; set; }

    public override string ToString() 
        /// Просто удобно выводит результат на экран, для удобства отладки
        => $"[({Inf} < {Sup}) на {Value}]";
}
